function jsonError(status, msg) {
  return new Response(JSON.stringify({ error: msg }), {
    status,
    headers: { 'Content-Type': 'application/json' },
  });
}

// 容错解析请求体：Reeden 对 {{text}} 做裸替换，正文里的换行/引号会破坏 JSON 结构
// （实测复现：文本含字面换行 → JSON.parse 抛错 → 400 请求体不是有效的 JSON）
// 策略：先严格解析；失败则按结构锚点宽松提取 model/input/voice。
function parseBody(raw) {
  // 1) 严格解析
  try {
    const j = JSON.parse(raw);
    if (j && typeof j === 'object') return j;
  } catch {}

  // 2) 宽松提取。配置模板固定为 {"model":"...","input":"<正文>","voice":"..."}
  const out = {};
  const mModel = raw.match(/"model"\s*:\s*"([^"]*)"/);
  if (mModel) out.model = mModel[1];
  const mVoice = raw.match(/"voice"\s*:\s*"([^"]*)"/);
  if (mVoice) out.voice = mVoice[1];

  const mInput = raw.match(/"input"\s*:\s*"/);
  if (mInput) {
    const rest = raw.slice(mInput.index + mInput[0].length);
    // 结构结尾锚点：最后一个 ", "voice" 或 ", "model"（容忍有/无空格）
    let end = rest.length;
    for (const key of ['voice', 'model']) {
      const re = new RegExp(`",\\s*"${key}"`, 'g');
      let m, last = -1;
      while ((m = re.exec(rest)) !== null) last = m.index;
      if (last >= 0 && last < end) end = last;
    }
    out.input = rest.slice(0, end);
  }

  return Object.keys(out).length ? out : null;
}

// 若正文被 URL 编码（%E4%BD%86...），解码且解码结果含中文则采用解码值
function maybeDecode(text) {
  if (!text || !/%[0-9A-Fa-f]{2}/.test(text)) return text;
  try {
    const dec = decodeURIComponent(text);
    if (/[\u4e00-\u9fff]/.test(dec)) return dec;
  } catch {}
  return text;
}

export default {
  async fetch(request, env, ctx) {
    if (request.method !== 'POST') {
      return jsonError(405, '只支持 POST 请求');
    }

    // 鉴权
    const authHeader = request.headers.get('Authorization') || '';
    const token = authHeader.replace('Bearer ', '');
    if (!env.API_KEY || token !== env.API_KEY) {
      return jsonError(401, '认证失败：API Key 无效');
    }

    // 解析请求体（容错：Reeden 裸替换 {{text}} 会带换行/引号破坏 JSON）
    const rawText = await request.text();
    const body = parseBody(rawText);
    if (!body) {
      return jsonError(400, `请求体不是有效的 JSON: ${rawText.slice(0, 200)}`);
    }

    const text = maybeDecode(body.input || '');
    const rawVoice = body.voice || 'wenrou_yujie';
    const model = body.model || 'mimo-v2.5-tts-voicedesign';
    if (!text) {
      return jsonError(400, '缺少必填字段 input（要合成的文本）');
    }

    const desc = VOICE_DESCS[rawVoice];
    if (!desc) {
      return jsonError(400, `音色 "${rawVoice}" 不在音色库中。可用音色: ${Object.keys(VOICE_DESCS).join(', ')}`);
    }

    const baseUrl = (env.MIMO_BASE_URL || 'https://api.xiaomimimo.com/v1').replace(/\/$/, '');
    const payload = {
      model,
      messages: [
        { role: 'user', content: desc },
        { role: 'assistant', content: text },
      ],
      audio: { format: 'mp3', optimize_text_preview: false },
    };

    try {
      const t0 = Date.now();
      const resp = await fetch(baseUrl + '/chat/completions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'api-key': env.MIMO_API_KEY || '',
        },
        body: JSON.stringify(payload),
      });
      const t1 = Date.now();

      if (!resp.ok) {
        const errText = await resp.text();
        return jsonError(502, `MiMo API 错误 ${resp.status}: ${errText.slice(0, 300)}`);
      }

      const data = await resp.json();
      const b64 = data.choices?.[0]?.message?.audio?.data;
      if (!b64) {
        return jsonError(502, `MiMo 响应无音频数据: ${JSON.stringify(data).slice(0, 300)}`);
      }

      // base64 → 二进制
      const binary = atob(b64);
      const bytes = new Uint8Array(binary.length);
      for (let i = 0; i < binary.length; i++) {
        bytes[i] = binary.charCodeAt(i);
      }

      return new Response(bytes, {
        headers: {
          'Content-Type': 'audio/mpeg',
          'Cache-Control': 'no-cache',
          'X-Timing-Upstream-Ms': String(t1 - t0),
          'X-Timing-Total-Ms': String(Date.now() - t0),
        },
      });
    } catch (e) {
      return jsonError(500, `Worker 内部错误: ${e.message}`);
    }
  },
};
